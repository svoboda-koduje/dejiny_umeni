function obdobiDuchu(od, doRoku) {
  const delka = 2480 / 7, start = 1879, idxMichael = 6; // 354,29 roku
  const seznam = [];
  let k = Math.floor((od - start) / delka) - 1;
  for (; ; k++) {
    const zac = Math.ceil(start + k * delka), kon = Math.ceil(start + (k + 1) * delka);
    if (zac > doRoku) break;
    if (kon < od) continue;
    const idx = ((idxMichael + k) % 7 + 7) % 7;
    seznam.push({ duch: DUCHOVE[idx], od: zac, do: kon });
  }
  return seznam;
}

